#!/usr/bin/env node
// Regenerates app/assets/stylesheets/application/_generated_imports.scss.
//

// Run automatically as part of `yarn build:css` (see package.json).
// This script recreates the "drop a file in the directory and it's automatically included"
// behavior previously provided by sassc-rails but lacking in dart-sass.
// Adding a new file requires a fresh build to pick it up; under `sass --watch`, that
// means restarting the watcher (see docs/code_patterns_and_conventions.md, "View Asset Management").

const fs = require('fs');
const path = require('path');

const STYLESHEETS_ROOT = path.join(__dirname, '..', 'app', 'assets', 'stylesheets');
const APPLICATION_DIR = path.join(STYLESHEETS_ROOT, 'application');
const OUTPUT_FILE = path.join(APPLICATION_DIR, '_generated_imports.scss');

// Matches the directories application.scss used to glob-import, in the same order.
const GLOBBED_DIRS = [
  'base',
  'elements',
  'objects',
  'components',
  'layouts',
  'modules',
  'overrides',
  'utilities',
];

function findScssFilesRecursive(dir) {
  let results = [];
  // Plain code-unit comparison, not localeCompare — locale-aware collation
  // can sort punctuation (e.g. a leading "_") differently than the byte-wise
  // sort this order was verified against (see plan doc, Phase 1 findings).
  const entries = fs.readdirSync(dir, { withFileTypes: true })
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));

  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      results = results.concat(findScssFilesRecursive(fullPath));
    } else if (entry.name.endsWith('.scss')) {
      results.push(fullPath);
    }
  }

  return results;
}

const lines = [
  '// AUTO-GENERATED by bin/generate_sass_imports.js — DO NOT EDIT BY HAND.',
  '// Regenerated on every `yarn build:css`. Add or remove .scss files in',
  `// application/{${GLOBBED_DIRS.join(',')}}/ (any depth) and this file`,
  '// updates itself on the next build.',
  '',
];

for (const dirName of GLOBBED_DIRS) {
  const dirPath = path.join(APPLICATION_DIR, dirName);
  for (const filePath of findScssFilesRecursive(dirPath)) {
    const importPath = path.relative(STYLESHEETS_ROOT, filePath).replace(/\.scss$/, '');
    lines.push(`@import '${importPath}';`);
  }
}

fs.writeFileSync(OUTPUT_FILE, lines.join('\n') + '\n');
console.log(`Wrote ${lines.length - 5} imports to ${path.relative(process.cwd(), OUTPUT_FILE)}`);
